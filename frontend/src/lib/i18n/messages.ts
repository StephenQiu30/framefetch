export type MessageTree = typeof zhCN;

type Join<Prefix extends string, Key extends string> = Prefix extends ''
  ? Key
  : `${Prefix}.${Key}`;

type Leaves<T, Prefix extends string = ''> = {
  [Key in keyof T & string]: T[Key] extends string
    ? Join<Prefix, Key>
    : Leaves<T[Key], Join<Prefix, Key>>;
}[keyof T & string];

export type MessageKey = Leaves<MessageTree>;

const catalogs: Record<'zh-CN' | 'en-US', Widen<typeof zhCN>> = {
  'zh-CN': zhCN,
  'en-US': enUS,
} as const;

export function translate(
  locale: 'zh-CN' | 'en-US',
  key: MessageKey,
  values?: Record<string, string | number>,
): string {
  const value = key.split('.').reduce<unknown>((node, part) => {
    if (node && typeof node === 'object' && part in node) {
      return (node as Record<string, unknown>)[part];
    }
    return undefined;
  }, catalogs[locale]);
  if (typeof value !== 'string') return key;
  if (!values) return value;
  return value.replace(/\{(\w+)\}/g, (_, name: string) =>
    values[name] === undefined ? '' : String(values[name]),
  );
}
